package com.neogul.whynago.question.infra.ai.prompt;

// v7까지의 꼬리질문 지시는 "직전 답변에서 한 단계만 더 깊게"라는 한 가지 규칙뿐이었다. 그래서 같은
// 문항을 푼 두 사람이 루브릭을 몇 개 충족했든, 숙련도가 MASTERED든 WEAK든 거의 같은 깊이의 꼬리질문을
// 받았다. 이미 다 아는 사람에게는 되묻는 질문이 되고, 개념이 없는 사람에게는 여전히 벅찬 질문이 된다.
//
// v8은 같은 호출에서 모델이 방금 산출한 두 판정을 꼬리질문의 입력으로 못 박는다.
// - 루브릭 결과(criteriaResults): met이 false인 항목이 이번 답변에서 비어 있던 지점이다.
//   그 지점을 스스로 메우게 하는 질문을 만들게 한다.
// - 숙련도(mastery): 여섯 등급마다 꼬리질문을 어느 깊이에서 물어야 하는지 등급별로 지정한다.
//
// 모름 답변은 그 등급별 지시만으로는 부족해 따로 다룬다. v7까지는 모른다고 하면 꼬리질문을 낮추라고만 했고,
// 그래서 눈높이는 내려가도 여전히 맨바닥에서 다시 묻는 질문이 나왔다. 아무것도 모르는 상태에서
// 더 쉬운 질문을 받아도 답할 실마리가 없기는 마찬가지다.
// v8은 모름 답변에 한해 꼬리질문 앞에 실마리를 한 줄 붙이게 하고, 그 실마리를 문항의 루브릭에서 끌어온다.
// 루브릭에는 이 문항이 확인하려는 내용이 이미 적혀 있으므로, 충족하지 못한 항목 중 가장 기초적인 하나를
// 전문 용어 없이 풀어 주면 정답을 흘리지 않으면서도 답변자가 생각을 시작할 지점이 된다.
// 학습을 이어 가려면 답할 수 있는 질문이어야 하고, 답할 수 있게 만드는 최소한이 그 한 줄이다.
//
// 다만 초기 v8은 실마리를 준 뒤 던지는 질문을 "그 한 줄만으로 답할 수 있는 질문"으로만 규정했다.
// 그 결과 실마리와 질문이 원래 문항에서 떨어져 나가, 답변자가 그 질문에 답해도 원래 물음에는
// 한 발짝도 가까워지지 않는 경우가 나왔다. 모름 답변에서 개념을 갈아타면 그 문항은 그대로 미해결로
// 남고, 세션은 3턴 안에 다른 이야기만 하다 끝난다.
// 지금의 v8은 모름 답변에서 질문의 대상을 원래 문항으로 고정한다. 실마리는 여전히 루브릭에서 끌어오되,
// 이어지는 질문은 원래 물음을 한 조각으로 좁힌 것이어야 하고 그 조각에 답하면 원래 답의 일부가
// 만들어져야 한다. 인접 개념으로 눈높이를 낮추는 것이 아니라, 같은 물음을 답할 수 있는 크기로 쪼갠다.
//
// 실마리에서 루브릭의 존재를 드러내지 않는 것도 함께 못 박는다. "이 문제가 확인하려는 것은" 같은
// 채점 기준 해설이 앞에 붙으면 답변자는 문제를 푸는 대신 채점 설명을 읽게 되고,
// 무엇을 쓰면 점수를 받는지가 노출돼 이해도 확인이 아니라 받아쓰기가 된다.
//
// 실마리를 고정 예시로 주지 않는 것은 의도적이다. 프롬프트에 구체적인 예시 문답을 넣었더니 모델이
// 그 문장을 무관한 문항의 꼬리질문에 그대로 옮겨 썼다(v6-v8 비교 리포트의 tcp-partial-answer).
// 실마리의 출처를 지금 채점 중인 문항의 루브릭으로 못 박아 옮겨 쓸 원본 자체를 없앤다.
//
// 대신 형식을 지정한다. 예시를 없애자 누출은 멎었지만 실마리 자체가 사라지고 질문 한 줄만 남았다.
// "풀어서 앞에 붙여라"는 서술만으로는 작은 모델이 형태를 잡지 못한다. 그래서 내용은 루브릭에서 오게 두고
// 골격만 - 서술문 한 문장 뒤에 질문 한 문장 - 못 박는다. 형식에는 옮겨 쓸 내용이 없어 누출되지 않는다.
//
// 채점과 꼬리질문 생성이 한 번의 호출에서 함께 나오므로 별도 입력을 더할 필요가 없다.
// 다만 모델이 꼬리질문을 먼저 쓰고 판정을 나중에 맞추면 개인화가 무의미해지므로,
// criteriaResults와 mastery를 먼저 확정한 뒤 그 결과를 보고 꼬리질문을 쓰라고 순서를 지시한다.
//
// 루브릭이 없는 턴(꼬리질문 턴·루브릭 미보유 문항)에서는 criteriaResults가 빈 배열이므로
// 루브릭 절은 자연히 적용되지 않고 숙련도 절만 남는다.
public class EssayPromptV8 extends EssayPromptV7 {

    private static final String VERSION = "v8";

    private static final String PERSONALIZED_FOLLOWUP_INSTRUCTION = """


            꼬리질문은 방금 네가 내린 판정에 맞춰 정하라. 판정과 무관하게 늘 같은 깊이로 묻지 마라.
            criteriaResults와 mastery를 먼저 확정한 뒤, 그 결과를 보고 followupQuestion을 만들어라.
            꼬리질문은 masteryReason과 모순되지 않아야 한다.
            masteryReason에서 빠졌거나 흔들린다고 짚은 지점이 꼬리질문이 향할 곳이다.

            criteriaResults를 채운 턴이라면 루브릭 판정을 기준으로 삼아라.
            - met이 false인 항목이 있으면 그중 답변자가 가장 가까이 다가간 항목 하나만 골라,
              그 항목의 내용을 스스로 떠올릴 수 있게 물어라. 미충족 항목 여러 개를 한 질문에 몰아 담지 마라.
            - 항목의 문장을 그대로 읽어 주고 맞는지 되묻지 마라. 답이 질문 안에 드러나면 이해도가 확인되지 않는다.
              그 항목이 다루는 상황을 묻고 답변자가 개념을 꺼내 오게 하라.
            - 모든 항목이 met이면 루브릭이 이미 확인한 내용을 다시 묻지 말고,
              그 내용을 실제 상황에 적용하면 어떻게 되는지로 한 단계만 넓혀라.

            mastery 판정별로 꼬리질문의 깊이를 다음과 같이 맞춰라.
            MASTERED: 개념의 경계나 예외 상황, 선택의 트레이드오프를 물어라. 이미 설명한 내용을 되묻지 마라.
            SOLID: 갖춘 근거를 구체적인 상황에 적용하면 어떻게 되는지 한 단계만 더 물어라.
            UNSTABLE: 깊이를 더하지 마라. 흔들린 근거를 스스로 되짚게 하는 질문을 같은 깊이에서 물어라.
                      결론을 다시 묻지 말고 왜 그렇게 되는지를 물어라.
            GUESSED: 답변자가 나열한 용어 중 하나를 골라 그것이 무엇을 하는지 자기 말로 설명하게 물어라.
                     새로운 용어를 더하지 마라.
            WEAK: 틀린 결론을 정면으로 반박해 다시 묻지 마라. 그 오개념이 성립하지 않는 가장 단순한 상황을
                  스스로 떠올리게 하는 질문으로 눈높이를 낮춰라.
            NOT_LEARNED: 개념을 그대로 다시 묻지 마라. 대신 원래 질문을 답할 수 있는 크기로 쪼개어,
                         그 첫 조각을 실마리와 함께 물어라. 자세한 방법은 아래 모름 답변 절을 따르라.

            mastery가 GUESSED, WEAK, NOT_LEARNED 중 하나라면 어떤 경우에도 직전 답변보다 깊이를 더하지 마라.
            그 세 등급에서는 새로운 개념을 확인하는 것이 아니라 답변자가 딛고 설 지점을 찾는 것이 목적이다.

            답변자가 '모르겠다', '잘 모른다', '기억이 안 난다'처럼 모름을 밝히면 NOT_LEARNED로 다루되,
            묻는 대상을 다른 개념으로 갈아타지 마라. 원래 질문을 그대로 두고, 답변자가 거기에 스스로
            답할 수 있도록 실마리를 준 뒤 그 질문의 첫 조각만 떼어 물어라.
            모름 답변에 한해 이 절이 앞의 모든 지시보다 우선한다. 다른 측면으로 질문을 틀라는 지시나
            더 기초적인 인접 개념으로 낮추라는 지시는 여기서는 적용하지 않는다.
            눈높이를 낮추는 방법은 다른 개념으로 옮겨 가는 것이 아니라, 같은 질문을 더 작게 쪼개는 것이다.

            실마리의 내용은 이 문항의 채점 기준에서 끌어오되, 채점 기준이 있다는 사실 자체는 드러내지 마라.
            '채점 기준', '평가 항목', '이 문제가 확인하려는 것은', '이 문항의 핵심은' 같은 말을 쓰지 말고
            무엇을 평가하려 했는지 설명하지도 마라. 실마리는 상황 하나를 알려 주는 한 줄일 뿐이다.

            - 충족하지 못한 항목 중 가장 기초적인 것 하나를 고른다. 배점이 큰 항목이 대개 그 문항의 핵심이다.
            - 그 항목이 말하는 내용을 전문 용어 없이 일상적인 말로 한 줄 풀어 followupQuestion 앞에 붙인다.
              항목 문장을 그대로 옮기거나 용어의 정의를 그대로 주지 마라.
              답을 알려 주는 것이 아니라 답변자가 생각을 시작할 지점을 주는 것이다.
            - 이어지는 질문은 원래 질문을 한 조각으로 좁힌 것이어야 한다.
              그 조각에 답하면 원래 질문의 답 일부가 저절로 만들어지는 질문을 골라라.
              원래 질문과 무관한 다른 개념으로 옮겨 가지 마라.
            - 그 조각은 앞의 한 줄만으로 답할 수 있을 만큼 작아야 한다.
              용어의 이름을 대게 하지 말고, 그 상황에서 무엇이 문제가 되는지, 왜 그렇게 되는지를
              자기 말로 답하게 물어라.

            이때의 followupQuestion은 반드시 두 문장으로 쓴다.
            첫 문장은 위에서 푼 한 줄이며, 묻지 말고 서술로 끝낸다. 물음표를 붙이지 마라.
            둘째 문장이 실제로 묻는 질문이고, 원래 질문을 좁힌 것이면서 첫 문장이 말한 상황 안에서
            답할 수 있어야 한다. 첫 문장에 답을 담지 말고, 답변자가 모른다고 한 용어도 넣지 마라.

            실마리를 준 뒤에도 다시 모른다고 하면 그때도 개념을 갈아타지 마라.
            앞서 준 실마리보다 더 구체적인 상황을 한 줄로 제시하고, 질문을 한 번 더 좁혀라.
            둘 중 어느 쪽인지 고르거나 어떤 일이 벌어질지 예상해 답할 수 있는 수준까지 낮춰도 된다.

            채점 기준이 주어지지 않은 턴이라면 항목 대신, 그 질문에 답하려면 가장 먼저 떠올려야 하는 관찰
            하나를 같은 방식으로 한 줄 풀어 주고, 그 질문을 좁혀 물어라.

            모른다고 한 용어를 다시 정의하라고 요구하거나, 새 심화 용어를 꺼내는 질문은 금지한다.
            원래 질문의 대상을 유지하는 것과 모른다고 한 용어를 다시 묻는 것은 다르다.
            대상은 그대로 두되 그 용어는 빼고, 용어가 가리키던 것을 상황으로 풀어 물어라.
            이 방식은 모름을 밝힌 답변에만 쓴다. 부분 정답이나 오답에는 실마리를 붙이지 말고
            위의 등급별 지시를 따르라. 다른 문항에서 본 개념이나 문장을 지금 채점 대상에 옮겨 쓰지 마라.""";

    @Override
    public String version() {
        return VERSION;
    }

    @Override
    protected String generateFollowupInstruction() {
        return super.generateFollowupInstruction() + PERSONALIZED_FOLLOWUP_INSTRUCTION;
    }
}
