-- 로컬(local) 프로파일 참고용 추가 시드: DB 카테고리 1회차 — 객관식 25문항 + 서술형 50문항 = 총 75문항.
-- docs/TAG.md(태그 사전) + docs/SCRIPT.md(객관식) + docs/SCRIPT_ESSAY.md(서술형) 규칙으로 생성했다.
--
-- 생성 방식: 태그 사전을 먼저 확정하고 태그를 축으로 문항을 만들었다.
--   객관식(MULTIPLE_CHOICE, 25개): 태그 25개를 5개 클러스터 × 5개로 나누고,
--     클러스터 1개 = 그룹 1개(본질문 1 + 그 보기 4개에 연결된 꼬리질문 4개) = 5문항.
--     태그 25개와 문항 25개가 1:1이며, 각 태그가 정확히 1회씩 주 태그로 쓰였다.
--     "본질문"·"꼬리질문"은 생성 순서를 가리키는 표현일 뿐 도메인/DB에는 엔티티 차원의 구분이 없다 —
--     모든 question 행은 동등한 독립 문항이며 문제은행에 노출된다.
--     본질문의 보기 K는 @qN_K로, 꼬리질문의 보기 4개는 전부 부모 @qN으로 되돌아가는 순환 연결이다.
--     따라서 answer_choice.related_question_id에 NULL이 하나도 없다.
--     정답 보기의 위치(sequence)는 문항마다 1~4로 무작위 분산되어 있다.
--   서술형(ESSAY, 50개): 같은 태그 25개에 대해 태그당 2문항. 두 문항은 같은 태그의 서로 다른 측면을 묻는다.
--     서술형은 본 질문만 저장하며(꼬리질문은 풀이 세션마다 AI가 동적 생성) answer_choice가 없다.
--     ※ SCRIPT_ESSAY.md의 "회차 내 주 태그 중복 금지" 규칙에 대한 의도된 예외다(태그당 2문항 요청).
--
-- id는 AUTO_INCREMENT이며, 문항 간 연결과 태그 부여는 세션 변수(@qN, @qN_K, @eN)로 캡처한 실제 id를 쓴다.
-- 대입은 = 를 쓴다(H2 MySQL 호환모드에서 := 는 문법 오류).
--
-- 기본 설정으로는 자동 로드되지 않는다. 적용하려면 application-db-local.yml의
-- spring.sql.init.data-locations에 classpath:data3.sql을 추가한다.

